import { spawnSync } from "node:child_process"
import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { extname, join } from "node:path"
import { pathToFileURL } from "node:url"

const CHANGED_LINE_SUPPORTED_EXTENSIONS = new Set([
  ".cjs",
  ".css",
  ".cts",
  ".gql",
  ".graphql",
  ".js",
  ".json",
  ".jsonc",
  ".jsx",
  ".mjs",
  ".mts",
  ".ts",
  ".tsx",
])
const LINT_RATCHET_SUPPORTED_EXTENSIONS = new Set([
  ...CHANGED_LINE_SUPPORTED_EXTENSIONS,
  ".html",
  ".svg",
])
export const COMMAND_MAX_BUFFER_BYTES = 64 * 1024 * 1024
export const BIOME_JSON_MAX_BUFFER_BYTES = COMMAND_MAX_BUFFER_BYTES
export const LINT_BASELINE_PATH = "lint-baseline.json"
export const LINT_BASELINE_POLICY =
  "Generated by scripts/run-biome-changed.mjs --update-lint-baseline. Blocking counts may only shrink; new files start at zero. A pure rename may move an unchanged count to the new path. Perform unrelated mechanical cleanup in separate batches."

function git(args) {
  const result = spawnSync("git", args, {
    encoding: "utf8",
    maxBuffer: COMMAND_MAX_BUFFER_BYTES,
    stdio: ["ignore", "pipe", "inherit"],
  })
  if (result.error) throw result.error
  if (result.status !== 0) process.exit(result.status ?? 1)
  return result.stdout
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
}

function gitText(args) {
  const result = spawnSync("git", args, {
    encoding: "utf8",
    maxBuffer: COMMAND_MAX_BUFFER_BYTES,
    stdio: ["ignore", "pipe", "inherit"],
  })
  if (result.error) throw result.error
  if (result.status !== 0) process.exit(result.status ?? 1)
  return result.stdout
}

function readGitObjectText(reference, path) {
  const commitCheck = spawnSync(
    "git",
    ["cat-file", "-e", `${reference}^{commit}`],
    {
      encoding: "utf8",
      maxBuffer: COMMAND_MAX_BUFFER_BYTES,
      stdio: ["ignore", "pipe", "pipe"],
    },
  )
  if (commitCheck.error) throw commitCheck.error
  if (commitCheck.status !== 0) {
    throw new Error(`Git baseline reference ${reference} is unavailable.`)
  }

  const result = spawnSync("git", ["show", `${reference}:${path}`], {
    encoding: "utf8",
    maxBuffer: COMMAND_MAX_BUFFER_BYTES,
    stdio: ["ignore", "pipe", "pipe"],
  })
  if (result.error) throw result.error
  if (result.status !== 0) return null
  return result.stdout
}

export function parseGitNameStatusZ(text) {
  const fields = text.split("\0")
  if (fields.at(-1) === "") fields.pop()

  const paths = new Set()
  const renames = new Map()
  for (let index = 0; index < fields.length; ) {
    const status = fields[index++]
    if (!status) continue

    if (status.startsWith("R") || status.startsWith("C")) {
      const oldPath = fields[index++]
      const newPath = fields[index++]
      if (!oldPath || !newPath) {
        throw new Error(`Malformed git name-status record for ${status}.`)
      }
      paths.add(normalizePath(oldPath))
      paths.add(normalizePath(newPath))
      if (status === "R100") {
        renames.set(normalizePath(oldPath), normalizePath(newPath))
      }
      continue
    }

    const path = fields[index++]
    if (!path) {
      throw new Error(`Malformed git name-status record for ${status}.`)
    }
    paths.add(normalizePath(path))
  }

  return { paths, renames }
}

export function isChangedLineSupportedPath(path) {
  return CHANGED_LINE_SUPPORTED_EXTENSIONS.has(extname(path))
}

export function isLintRatchetSupportedPath(path) {
  return LINT_RATCHET_SUPPORTED_EXTENSIONS.has(extname(path))
}

function isAllZeroSha(value) {
  return /^0{40}$/i.test(value)
}

function normalizePath(path) {
  return path.replace(/\\/g, "/").replace(/^\.\//, "")
}

function compareCodePoints(left, right) {
  return left < right ? -1 : left > right ? 1 : 0
}

function addChangedLine(changeMap, path, line) {
  const normalizedPath = normalizePath(path)
  const entry = changeMap.get(normalizedPath) ?? { lines: new Set() }
  entry.lines.add(line)
  changeMap.set(normalizedPath, entry)
}

export function collectChangedLinesFromUnifiedDiff(diffText) {
  const changeMap = new Map()
  let currentPath = null

  for (const line of diffText.split("\n")) {
    if (line.startsWith("+++ ")) {
      const nextPath = line.slice(4).trim()
      currentPath = nextPath.startsWith("b/") ? nextPath.slice(2) : null
      continue
    }

    if (!currentPath || !line.startsWith("@@ ")) {
      continue
    }

    const match = line.match(/\+(\d+)(?:,(\d+))?/)
    if (!match) {
      continue
    }

    const start = Number.parseInt(match[1], 10)
    const count = match[2] ? Number.parseInt(match[2], 10) : 1
    for (let offset = 0; offset < count; offset += 1) {
      addChangedLine(changeMap, currentPath, start + offset)
    }
  }

  return changeMap
}

export function markAllLinesChanged(changeMap, paths) {
  const next = new Map(changeMap)
  for (const path of paths) {
    next.set(normalizePath(path), { allLines: true, lines: new Set() })
  }
  return next
}

function hasChangedLineInRange(change, startLine, endLine) {
  if (change.allLines) return true
  for (let line = startLine; line <= endLine; line += 1) {
    if (change.lines.has(line)) return true
  }
  return false
}

export function diagnosticTouchesChangedLines(diagnostic, changeMap) {
  const path = diagnostic?.location?.path
  if (!path) return false

  const change = changeMap.get(normalizePath(path))
  if (!change) return false
  if (change.allLines) return true

  const startLine = diagnostic?.location?.start?.line
  if (typeof startLine !== "number") {
    return true
  }

  const endLine =
    typeof diagnostic?.location?.end?.line === "number"
      ? diagnostic.location.end.line
      : startLine
  return hasChangedLineInRange(change, startLine, endLine)
}

export function filterDiagnosticsForChangedLines(diagnostics, changeMap) {
  return diagnostics.filter((diagnostic) =>
    diagnosticTouchesChangedLines(diagnostic, changeMap),
  )
}

export function isBlockingChangedDiagnostic(diagnostic) {
  return diagnostic?.severity === "error" || diagnostic?.severity === "warning"
}

export function countBlockingDiagnosticsByFile(diagnostics) {
  const counts = new Map()
  for (const diagnostic of diagnostics) {
    if (!isBlockingChangedDiagnostic(diagnostic)) continue
    const diagnosticPath = diagnostic?.location?.path
    if (!diagnosticPath) continue
    const path = normalizePath(diagnosticPath)
    counts.set(path, (counts.get(path) ?? 0) + 1)
  }
  return counts
}

export function createLintBaselineDocument(counts) {
  const files = {}
  const normalizedCounts = new Map()
  for (const [path, count] of counts) {
    const normalizedPath = normalizePath(path)
    normalizedCounts.set(
      normalizedPath,
      (normalizedCounts.get(normalizedPath) ?? 0) + count,
    )
  }
  for (const [path, count] of [...normalizedCounts.entries()].sort(
    ([left], [right]) => compareCodePoints(left, right),
  )) {
    if (Number.isInteger(count) && count > 0) {
      files[path] = count
    }
  }
  return { $comment: LINT_BASELINE_POLICY, files }
}

function lintBaselineFiles(document) {
  if (!document || typeof document !== "object") {
    throw new Error(`${LINT_BASELINE_PATH} must contain a JSON object.`)
  }
  if (!document.files || typeof document.files !== "object") {
    throw new Error(`${LINT_BASELINE_PATH} must contain a files object.`)
  }
  if (document.$comment !== LINT_BASELINE_POLICY) {
    throw new Error(
      `${LINT_BASELINE_PATH} must keep the canonical generated-only policy header.`,
    )
  }

  const files = {}
  for (const [path, count] of Object.entries(document.files)) {
    if (!Number.isInteger(count) || count <= 0) {
      throw new Error(
        `${LINT_BASELINE_PATH} ${path} must have a positive integer blocking count.`,
      )
    }
    const normalizedPath = normalizePath(path)
    if (path !== normalizedPath) {
      throw new Error(
        `${LINT_BASELINE_PATH} path ${path} must be normalized as ${normalizedPath}.`,
      )
    }
    if (!isLintRatchetSupportedPath(path)) {
      throw new Error(
        `${LINT_BASELINE_PATH} path ${path} is outside the normal full-file ratchet inventory. Add explicit ratchet coverage before generating that entry.`,
      )
    }
    files[path] = count
  }

  const canonical = createLintBaselineDocument(new Map(Object.entries(files)))
  if (JSON.stringify(document) !== JSON.stringify(canonical)) {
    throw new Error(
      `${LINT_BASELINE_PATH} must contain only the canonical policy and code-point-sorted files map.`,
    )
  }
  return files
}

export function evaluateTouchedFileLintBaseline({
  touchedFiles,
  diagnosticCounts,
  baselineDocument,
}) {
  const baseline = lintBaselineFiles(baselineDocument)
  const above = []
  const below = []

  for (const path of [...new Set(touchedFiles)].sort()) {
    const normalizedPath = normalizePath(path)
    const actual = diagnosticCounts.get(normalizedPath) ?? 0
    const expected = baseline[normalizedPath] ?? 0
    if (actual > expected) {
      above.push({ path: normalizedPath, actual, expected })
    } else if (actual < expected) {
      below.push({ path: normalizedPath, actual, expected })
    }
  }

  return { above, below }
}

export function planLintBaselineUpdate({
  existingDocument,
  measuredDocument,
  renames = new Map(),
}) {
  if (!existingDocument) {
    lintBaselineFiles(measuredDocument)
    return { ok: true, failures: [], document: measuredDocument }
  }

  const existing = lintBaselineFiles(existingDocument)
  const measured = lintBaselineFiles(measuredDocument)
  const oldPathByNewPath = new Map(
    [...renames.entries()].map(([oldPath, newPath]) => [
      normalizePath(newPath),
      normalizePath(oldPath),
    ]),
  )
  const failures = []

  for (const [path, count] of Object.entries(measured)) {
    const oldCount = existing[path]
    if (oldCount !== undefined) {
      if (count > oldCount) {
        failures.push(
          `${path} would raise its blocking baseline from ${oldCount} to ${count}.`,
        )
      }
      continue
    }

    const oldPath = oldPathByNewPath.get(path)
    const isPureRenameCarry =
      oldPath !== undefined &&
      existing[oldPath] === count &&
      measured[oldPath] === undefined
    if (!isPureRenameCarry) {
      failures.push(
        `${path} would add a blocking baseline entry of ${count}; new entries start at zero.`,
      )
    }
  }

  return {
    ok: failures.length === 0,
    failures,
    document: measuredDocument,
  }
}

export function resolveBiomeExecutable({
  cwd = process.cwd(),
  platform = process.platform,
  exists = existsSync,
} = {}) {
  const binaryName = platform === "win32" ? "biome.cmd" : "biome"
  const path = join(cwd, "node_modules", ".bin", binaryName)
  if (exists(path)) {
    return { ok: true, command: path, shell: platform === "win32" }
  }

  return {
    ok: false,
    error: `Biome executable not found at ${path}. Run \`bun install\` before linting.`,
  }
}

function formatDiagnostic(diagnostic) {
  const location = diagnostic.location
  const path = location?.path ?? "<unknown>"
  const line = location?.start?.line ?? "?"
  const column = location?.start?.column ?? "?"
  const category = diagnostic.category ? ` ${diagnostic.category}` : ""
  return `${diagnostic.severity}${category} ${path}:${line}:${column} ${diagnostic.message}`
}

function parseBiomeJson(stdout) {
  try {
    return JSON.parse(stdout)
  } catch (error) {
    throw new Error(`Failed to parse Biome JSON output: ${error.message}`)
  }
}

function getChangedLineMap(since) {
  if (!since) {
    const diffText = gitText([
      "diff",
      "--unified=0",
      "--diff-filter=ACMR",
      "HEAD",
    ])
    const untracked = git(["ls-files", "--others", "--exclude-standard"])
    return markAllLinesChanged(
      collectChangedLinesFromUnifiedDiff(diffText),
      untracked,
    )
  }

  if (isAllZeroSha(since)) {
    console.log(
      "BIOME_CHANGED_SINCE is the all-zero SHA; checking current HEAD diff.",
    )
    return getChangedLineMap(null)
  }

  return collectChangedLinesFromUnifiedDiff(
    gitText(["diff", "--unified=0", "--diff-filter=ACMR", `${since}...HEAD`]),
  )
}

function getTouchedFileMetadata(since) {
  if (!since) {
    const metadata = parseGitNameStatusZ(
      gitText([
        "diff",
        "--name-status",
        "-z",
        "--find-renames=100%",
        "--diff-filter=ACMRD",
        "HEAD",
      ]),
    )
    const untracked = gitText([
      "ls-files",
      "--others",
      "--exclude-standard",
      "-z",
    ])
      .split("\0")
      .filter(Boolean)
    for (const path of untracked) metadata.paths.add(normalizePath(path))
    return metadata
  }

  if (isAllZeroSha(since)) {
    return getTouchedFileMetadata(null)
  }

  return parseGitNameStatusZ(
    gitText([
      "diff",
      "--name-status",
      "-z",
      "--find-renames=100%",
      "--diff-filter=ACMRD",
      `${since}...HEAD`,
    ]),
  )
}

function getChangedFilesFromMap(changeMap) {
  return [...changeMap.keys()].filter(isChangedLineSupportedPath)
}

export function resolveChangedSince(env = process.env) {
  return (
    env.BIOME_CHANGED_SINCE?.trim() || env.DIFF_BASE_SHA?.trim() || undefined
  )
}

function runBiome(command, shell, files) {
  return spawnSync(command, ["check", "--reporter=json", ...files], {
    encoding: "utf8",
    maxBuffer: COMMAND_MAX_BUFFER_BYTES,
    stdio: ["ignore", "pipe", "pipe"],
    shell,
  })
}

export function parseValidatedBiomeResult(result, { expectedFiles } = {}) {
  if (result.error) throw result.error
  if (result.signal) {
    throw new Error(`Biome was terminated by signal ${result.signal}.`)
  }

  const output = parseBiomeJson(result.stdout)
  if (!output || typeof output !== "object") {
    throw new Error("Biome JSON output must be an object.")
  }
  if (
    !Array.isArray(output.diagnostics) ||
    !output.summary ||
    typeof output.summary !== "object"
  ) {
    throw new Error("Biome JSON output is missing diagnostics or summary data.")
  }
  const summaryCounts = ["errors", "warnings", "infos", "diagnosticsNotPrinted"]
  for (const field of summaryCounts) {
    if (!Number.isInteger(output.summary[field]) || output.summary[field] < 0) {
      throw new Error(`Biome summary.${field} must be a non-negative integer.`)
    }
  }
  if (output.summary.diagnosticsNotPrinted > 0) {
    throw new Error(
      "Biome omitted diagnostics; refusing to evaluate an incomplete lint result.",
    )
  }

  const printedCounts = { errors: 0, warnings: 0, infos: 0 }
  for (const diagnostic of output.diagnostics) {
    const summaryField =
      diagnostic?.severity === "error"
        ? "errors"
        : diagnostic?.severity === "warning"
          ? "warnings"
          : diagnostic?.severity === "info"
            ? "infos"
            : null
    if (!summaryField) {
      throw new Error(
        `Biome reported an unsupported diagnostic severity ${JSON.stringify(diagnostic?.severity)}.`,
      )
    }
    printedCounts[summaryField] += 1
  }
  for (const field of ["errors", "warnings", "infos"]) {
    if (printedCounts[field] !== output.summary[field]) {
      throw new Error(
        `Biome summary.${field}=${output.summary[field]} does not match ${printedCounts[field]} printed diagnostics.`,
      )
    }
  }

  const expectedPathSet = expectedFiles
    ? new Set(expectedFiles.map(normalizePath))
    : null
  for (const diagnostic of output.diagnostics) {
    if (!isBlockingChangedDiagnostic(diagnostic)) continue
    const diagnosticPath = diagnostic?.location?.path
    if (typeof diagnosticPath !== "string" || diagnosticPath.length === 0) {
      throw new Error(
        "Biome reported a blocking diagnostic without a file path; refusing to drop a global or configuration failure.",
      )
    }
    const normalizedDiagnosticPath = normalizePath(diagnosticPath)
    if (expectedPathSet && !expectedPathSet.has(normalizedDiagnosticPath)) {
      throw new Error(
        `Biome reported a blocking diagnostic for unexpected path ${normalizedDiagnosticPath}.`,
      )
    }
  }

  const internalDiagnostics = output.diagnostics.filter((diagnostic) =>
    String(diagnostic?.category ?? "").startsWith("internalError"),
  )
  if (internalDiagnostics.length > 0) {
    throw new Error(
      `Biome reported an internal error: ${internalDiagnostics
        .map((diagnostic) => diagnostic.message)
        .join("; ")}`,
    )
  }

  const status = typeof result.status === "number" ? result.status : 1
  if (status !== 0) {
    const hasOrdinaryBlockingDiagnostic = output.diagnostics.some(
      isBlockingChangedDiagnostic,
    )
    if (status !== 1 || !hasOrdinaryBlockingDiagnostic) {
      throw new Error(
        `Biome exited ${status} without a complete ordinary lint/format diagnostic result.`,
      )
    }
  }

  return output
}

function readLintBaseline() {
  if (!existsSync(LINT_BASELINE_PATH)) {
    throw new Error(
      `${LINT_BASELINE_PATH} is missing. Run \`bun run lint:changed -- --update-lint-baseline\` to bootstrap it.`,
    )
  }
  return JSON.parse(readFileSync(LINT_BASELINE_PATH, "utf8"))
}

function readAuthoritativeLintBaseline(since) {
  const reference = since && !isAllZeroSha(since) ? since : "HEAD"
  const text = readGitObjectText(reference, LINT_BASELINE_PATH)
  return text === null
    ? { document: null, reference }
    : {
        document: JSON.parse(text),
        reference,
      }
}

function assertOnlyShrinkFromAuthoritativeBaseline({
  authoritativeDocument,
  currentDocument,
  renames,
  reference,
}) {
  if (!authoritativeDocument) return
  const plan = planLintBaselineUpdate({
    existingDocument: authoritativeDocument,
    measuredDocument: currentDocument,
    renames,
  })
  if (!plan.ok) {
    throw new Error(
      `${LINT_BASELINE_PATH} raises debt relative to ${reference}: ${plan.failures.join(" ")}`,
    )
  }
}

function updateLintBaseline(biome) {
  const result = runBiome(biome.command, biome.shell, ["."])
  const output = parseValidatedBiomeResult(result)
  const diagnostics = output.diagnostics

  const counts = countBlockingDiagnosticsByFile(diagnostics)
  const measuredDocument = createLintBaselineDocument(counts)
  const since = resolveChangedSince()
  const { renames } = getTouchedFileMetadata(since)
  const authoritative = readAuthoritativeLintBaseline(since)
  const plan = planLintBaselineUpdate({
    existingDocument: authoritative.document,
    measuredDocument,
    renames,
  })
  if (!plan.ok) {
    for (const failure of plan.failures) console.error(`- ${failure}`)
    throw new Error(
      `Refusing to raise lint debt relative to ${authoritative.reference}. Baseline raises require Owner approval; fix the diagnostics instead.`,
    )
  }

  writeFileSync(
    LINT_BASELINE_PATH,
    `${JSON.stringify(plan.document, null, 2)}\n`,
  )
  const total = [...counts.values()].reduce((sum, count) => sum + count, 0)
  console.log(
    `Updated ${LINT_BASELINE_PATH}: ${total} blocking diagnostics across ${counts.size} files.`,
  )
}

function main() {
  const biome = resolveBiomeExecutable()
  if (!biome.ok) {
    console.error(biome.error)
    process.exit(1)
  }

  if (process.argv.includes("--update-lint-baseline")) {
    updateLintBaseline(biome)
    process.exit(0)
  }

  const since = resolveChangedSince()
  const baselineDocument = readLintBaseline()
  lintBaselineFiles(baselineDocument)
  const changedLineMap = getChangedLineMap(since)
  const touchedMetadata = getTouchedFileMetadata(since)
  const authoritative = readAuthoritativeLintBaseline(since)
  assertOnlyShrinkFromAuthoritativeBaseline({
    authoritativeDocument: authoritative.document,
    currentDocument: baselineDocument,
    renames: touchedMetadata.renames,
    reference: authoritative.reference,
  })
  const touchedFiles = [
    ...new Set([
      ...getChangedFilesFromMap(changedLineMap),
      ...[...touchedMetadata.paths].filter(isLintRatchetSupportedPath),
    ]),
  ].sort()

  if (touchedFiles.length === 0) {
    console.log("No changed files supported by Biome.")
    process.exit(0)
  }

  const existingFiles = touchedFiles.filter((path) => existsSync(path))
  const result =
    existingFiles.length > 0
      ? runBiome(biome.command, biome.shell, existingFiles)
      : null
  const output = result
    ? parseValidatedBiomeResult(result, { expectedFiles: existingFiles })
    : {
        diagnostics: [],
        summary: {
          errors: 0,
          warnings: 0,
          infos: 0,
          diagnosticsNotPrinted: 0,
        },
      }
  const diagnostics = output.diagnostics
  const diagnosticCounts = countBlockingDiagnosticsByFile(diagnostics)
  const baselineResult = evaluateTouchedFileLintBaseline({
    touchedFiles,
    diagnosticCounts,
    baselineDocument,
  })
  const changedDiagnostics = filterDiagnosticsForChangedLines(
    diagnostics.filter((diagnostic) =>
      isChangedLineSupportedPath(diagnostic?.location?.path ?? ""),
    ),
    changedLineMap,
  )
  const changedBlockingDiagnostics = changedDiagnostics.filter(
    isBlockingChangedDiagnostic,
  )

  if (changedDiagnostics.length > 0) {
    console.error("Biome diagnostics on changed lines:")
    for (const diagnostic of changedDiagnostics) {
      console.error(`- ${formatDiagnostic(diagnostic)}`)
    }
  }

  if (baselineResult.above.length > 0) {
    console.error("Touched files exceed their full-file lint baseline:")
    for (const finding of baselineResult.above) {
      console.error(
        `- ${finding.path}: ${finding.actual} blocking diagnostics (baseline ${finding.expected})`,
      )
      for (const diagnostic of diagnostics.filter(
        (candidate) =>
          isBlockingChangedDiagnostic(candidate) &&
          normalizePath(candidate?.location?.path ?? "") === finding.path,
      )) {
        console.error(`  - ${formatDiagnostic(diagnostic)}`)
      }
    }
  }

  if (baselineResult.below.length > 0) {
    console.error(
      "Touched files are cleaner than their recorded lint baseline:",
    )
    for (const finding of baselineResult.below) {
      console.error(
        `- ${finding.path}: tighten ${LINT_BASELINE_PATH} from ${finding.expected} to ${finding.actual}${finding.actual === 0 ? " (remove the entry)" : ""}.`,
      )
    }
  }

  if (
    changedBlockingDiagnostics.length > 0 ||
    baselineResult.above.length > 0 ||
    baselineResult.below.length > 0
  ) {
    process.exit(1)
  }

  if (result && typeof result.status === "number" && result.status !== 0) {
    console.log(
      "Biome reported diagnostics only outside changed lines; ignoring legacy file diagnostics.",
    )
  }

  process.exit(0)
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  try {
    main()
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error))
    process.exit(1)
  }
}
